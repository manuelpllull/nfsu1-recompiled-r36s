#!/usr/bin/env python3
"""Per-call-site x87 depth changes for the local x87 window (see analyze.py):
  strip <gen>                 remove the annotations (RECOMP_ICALL_LW / RECOMP_CALL_LW -> plain forms)
  apply <gen> <info.json>     in every function of the scheme, RECOMP_ICALL(x) -> RECOMP_ICALL_LW(d, x) for each
                              indirect call, and RECOMP_CALL(f) -> RECOMP_CALL_LW(d, f) where f's depth change is
                              unknown (dynamic tail-jump thunks), d inferred by the analysis
  header <gen> <info.json> <out.h>   NFS_LW_<entry VA> / NFS_FPD_<function> constants
Run: strip, analyze.py, apply, header (ports/r36s/lw/lw.sh does all four)."""
import re, sys, json, glob, os
mode, gen = sys.argv[1], sys.argv[2]
FUNC = re.compile(r'^void (sub_[0-9A-F]{8})\(void\) \{', re.M)
STRIP1 = re.compile(r'RECOMP_ICALL_LW\(-?\d+, *')
STRIP2 = re.compile(r'RECOMP_CALL_LW\(-?\d+, *(sub_[0-9A-F]{8})\)')
if mode == 'strip':
    for f in sorted(glob.glob(gen + '/recomp_*.c')):
        s = open(f).read()
        t = STRIP2.sub(r'RECOMP_CALL(\1)', STRIP1.sub('RECOMP_ICALL(', s))
        if t != s: open(f, 'w').write(t)
    sys.exit(0)
info = json.load(open(sys.argv[3]))
if mode == 'header':
    out = open(sys.argv[4], 'w'); n = 0
    out.write('/* generated by ports/r36s/lw/annotate.py header: do not edit */\n#pragma once\n')
    names = set(info)
    for f in glob.glob(gen + '/recomp_*.c'):
        names.update(re.findall(r'RECOMP_CALL(?:_LW\(-?\d+, *)?\((sub_[0-9A-F]{8})\)', open(f).read()))
        names.update(re.findall(r'RECOMP_CALL_LW\(-?\d+, *(sub_[0-9A-F]{8})\)', open(f).read()))
    for nm in sorted(names):
        r = info.get(nm); lw = int(bool(r and r['lw'])); n += lw
        d = r['delta'] if r and r['delta'] is not None else 0
        k = r.get('k', 8) if r else 8
        out.write('#define NFS_LW_0x%su %d\n#define NFS_LWK_0x%su %d\n#define NFS_FPD_%s (%d)\n' % (nm[4:], lw, nm[4:], k, nm, d))
    print('functions in the scheme:', n, file=sys.stderr); sys.exit(0)
ICALL = re.compile(r'RECOMP_ICALL\(')
nfiles = nsites = 0
for f in sorted(glob.glob(gen + '/recomp_*.c')):
    s = open(f).read(); ms = list(FUNC.finditer(s)); parts = []; last = 0; changed = False
    for i, m in enumerate(ms):
        r = info.get(m.group(1)); end = ms[i+1].start() if i+1 < len(ms) else len(s)
        if not r or not r['lw'] or (not r['icd'] and not r['cgs']): continue
        body = s[m.end():end]
        icd = iter(r['icd'])
        def ic(mm):
            return 'RECOMP_ICALL_LW(%d, ' % next(icd)
        body2 = ICALL.sub(ic, body)
        assert next(icd, None) is None, m.group(1)
        for callee, d in r['cgs']:
            pat = 'RECOMP_CALL(%s)' % callee
            k = body2.find(pat); assert k >= 0, (m.group(1), callee)
            body2 = body2[:k] + 'RECOMP_CALL_LW(%d, %s)' % (d, callee) + body2[k + len(pat):]
        parts.append(s[last:m.end()]); parts.append(body2); last = end; changed = True
        nsites += len(r['icd']) + len(r['cgs'])
    if changed:
        parts.append(s[last:]); open(f, 'w').write(''.join(parts)); nfiles += 1
print('annotated', nsites, 'call sites in', nfiles, 'files', file=sys.stderr)
